"""
src/vdc/mathematics/throughput_formula.py

Central throughput resolution and measurement equations:
    V_actual(t) = min(V_desired(t), V_CPU(t), V_RAM(t), V_IO(t), [V_NET(t)])
    V_measured = actual_generated_bytes / elapsed_seconds

All throughput variables are expressed in effective generated bytes per second (B/s).
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Optional


@dataclass(frozen=True)
class ThroughputDecision:
    """
    Result of evaluating the resource-aware throughput minimum equation.
    Units: bytes per second (B/s).
    """
    actual_throughput_bps: float
    limiting_resource: str
    desired_bps: float
    cpu_bps: Optional[float]
    ram_bps: Optional[float]
    io_bps: Optional[float]
    net_bps: Optional[float]


def calculate_effective_throughput(
    desired_bps: float,
    cpu_bps: Optional[float] = None,
    ram_bps: Optional[float] = None,
    io_bps: Optional[float] = None,
    net_bps: Optional[float] = None,
) -> ThroughputDecision:
    """
    Compute effective throughput:
        V_actual = min(V_desired, V_CPU, V_RAM, V_IO, V_NET)

    Inputs must be >= 0 or None (if unmeasured/unconstrained).
    Units: bytes per second (B/s).

    Raises:
        ValueError: If any provided throughput is negative, NaN, or Infinite.
    """
    candidates: list[tuple[float, str]] = []

    def validate_and_add(val: Optional[float], name: str) -> None:
        if val is None:
            return
        if not isinstance(val, (int, float)):
            raise ValueError(f"{name} throughput must be numeric")
        if math.isnan(val) or math.isinf(val):
            raise ValueError(f"{name} throughput cannot be NaN or Infinite")
        if val < 0.0:
            raise ValueError(f"{name} throughput cannot be negative: {val}")
        candidates.append((float(val), name))

    validate_and_add(desired_bps, "desired")
    validate_and_add(cpu_bps, "cpu")
    validate_and_add(ram_bps, "ram")
    validate_and_add(io_bps, "io")
    validate_and_add(net_bps, "net")

    if not candidates:
        raise ValueError("At least one throughput limit must be provided")

    min_val, min_resource = min(candidates, key=lambda x: x[0])

    return ThroughputDecision(
        actual_throughput_bps=max(0.0, min_val),
        limiting_resource=min_resource,
        desired_bps=float(desired_bps),
        cpu_bps=cpu_bps,
        ram_bps=ram_bps,
        io_bps=io_bps,
        net_bps=net_bps,
    )


def calculate_measured_throughput(generated_bytes: int, elapsed_seconds: float) -> float:
    """
    Calculate real measured empirical throughput:
        V_measured = actual_generated_bytes / elapsed_seconds

    Args:
        generated_bytes: Actual recorded serialized output in bytes (>= 0).
        elapsed_seconds: Monotonic duration in seconds (> 0).

    Returns:
        Empirical rate in bytes per second.

    Raises:
        ValueError: If bytes < 0, elapsed_seconds <= 0, or inputs are NaN/Inf.
    """
    if not isinstance(generated_bytes, int) or generated_bytes < 0:
        raise ValueError(f"generated_bytes must be non-negative integer, got {generated_bytes}")
    if not isinstance(elapsed_seconds, (int, float)):
        raise ValueError("elapsed_seconds must be numeric")
    if math.isnan(elapsed_seconds) or math.isinf(elapsed_seconds):
        raise ValueError("elapsed_seconds cannot be NaN or Infinite")
    if elapsed_seconds <= 0.0:
        raise ValueError(f"elapsed_seconds must be strictly positive, got {elapsed_seconds}")

    return float(generated_bytes) / float(elapsed_seconds)
