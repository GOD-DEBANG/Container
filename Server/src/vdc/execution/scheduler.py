"""
src/vdc/execution/scheduler.py

Adaptive mathematical scheduler executing the 12-step scheduling sequence:
  1. Obtain a fresh resource snapshot.
  2. Validate memory admission and configured job limits.
  3. Calculate effective allowed throughput.
  4. Convert throughput into interval-specific byte budget.
  5. Convert budget into permitted work units.
  6. Admit only permitted work.
  7. Execute the work.
  8. Measure actual generated bytes and elapsed time.
  9. Update actual progress and remaining work.
  10. Apply bounded backpressure to generation and persistence.
  11. Recalculate resource limits on next scheduling interval.
  12. Stop only after target and validation requirements are satisfied.
"""

from __future__ import annotations

import time
from typing import Dict, List, Optional, Callable

from ..models.allocation_model import AllocationManifest
from ..models.execution_metrics import ExecutionMetrics, ResourceSnapshot
from ..models.subchunk_model import SubchunkModel
from ..mathematics.throughput_formula import (
    calculate_effective_throughput,
    calculate_measured_throughput,
)
from ..mathematics.progress_integrator import (
    calculate_remaining_bytes,
    calculate_progress_ratio,
)
from ..resource_engine.resource_monitor import ResourceMonitor
from ..resource_engine.resource_budget import ResourceBudget
from ..resource_engine.resource_enforcer import ResourceEnforcer
from ..layer2_processing.worker_manager import ProcessingWorkerManager


class AdaptiveScheduler:
    def __init__(
        self,
        budget: ResourceBudget,
        worker_manager: ProcessingWorkerManager,
        progress_callback: Optional[Callable[[float, int, int], None]] = None,
        deadline_monotonic: Optional[float] = None,
    ) -> None:
        self.budget = budget
        self.worker_manager = worker_manager
        self.progress_callback = progress_callback
        self.deadline_monotonic = deadline_monotonic
        self.enforcer = ResourceEnforcer(budget.scheduling_interval_seconds)
        self.is_cancelled = False

    def cancel(self) -> None:
        self.is_cancelled = True

    def schedule(
        self,
        manifest: AllocationManifest,
        metrics: ExecutionMetrics,
    ) -> Dict[str, str]:
        """
        Execute the 12-step scheduling loop across chunks in the manifest.
        Returns mapping of chunk_id -> storage path.
        """
        chunk_paths: Dict[str, str] = {}
        total_target_bytes = manifest.target_bytes
        actual_completed_bytes = 0
        actual_records_generated = 0

        # Group subchunks by chunk_id
        subchunks_by_chunk: Dict[str, List[SubchunkModel]] = {}
        for s in manifest.subchunks:
            subchunks_by_chunk.setdefault(s.chunk_id, []).append(s)

        # High-resolution monotonic timer for generation
        t_gen_start = time.perf_counter()

        for chunk in manifest.chunks:
            # Check cancellation or deadline
            if self.is_cancelled:
                raise InterruptedError("Execution cancelled by user or operator")
            if self.deadline_monotonic and time.monotonic() > self.deadline_monotonic:
                raise TimeoutError("Execution exceeded configured deadline")

            # Step 1: Obtain a fresh resource snapshot
            snapshot: ResourceSnapshot = ResourceMonitor.take_snapshot()
            metrics.resource_snapshots.append(snapshot)

            # Step 2: Validate memory admission
            if snapshot.ram_available_bytes < self.budget.memory_reserve_bytes:
                # Brief sleep to allow GC/memory recovery before retrying
                time.sleep(0.05)
                snapshot = ResourceMonitor.take_snapshot()
                if snapshot.ram_available_bytes < self.budget.memory_reserve_bytes:
                    metrics.limiting_resource = "RAM_EXHAUSTION"
                    raise MemoryError(
                        f"Memory budget breached: available {snapshot.ram_available_bytes} bytes "
                        f"below required reserve {self.budget.memory_reserve_bytes} bytes"
                    )

            # Step 3: Calculate effective allowed throughput
            # Simulated host constraint based on current CPU utilization
            cpu_factor = max(0.1, (100.0 - snapshot.cpu_percent) / 100.0)
            cpu_limit_bps = self.budget.target_throughput_bytes_per_sec * cpu_factor

            decision = calculate_effective_throughput(
                desired_bps=self.budget.target_throughput_bytes_per_sec,
                cpu_bps=cpu_limit_bps,
                ram_bps=None,
                io_bps=None,
            )
            metrics.limiting_resource = decision.limiting_resource

            # Step 4: Convert throughput into interval-specific byte budget
            _interval_budget = self.enforcer.calculate_interval_byte_budget(decision)

            # Step 5 & 6: Admit only permitted work
            subs = subchunks_by_chunk.get(chunk.chunk_id, [])

            # Step 7: Execute work
            t_chunk_start = time.perf_counter()
            paths = self.worker_manager.process_chunk(
                chunk=chunk,
                subchunks=subs,
                pacing_delay_seconds=self.budget.pacing_delay_seconds,
            )
            t_chunk_end = time.perf_counter()
            metrics.chunk_processing_seconds += (t_chunk_end - t_chunk_start)
            chunk_paths.update(paths)

            # Step 8: Measure actual generated bytes and elapsed time
            actual_completed_bytes += chunk.byte_length
            actual_records_generated += chunk.record_count

            # Step 9: Update actual progress and remaining work
            remaining = calculate_remaining_bytes(total_target_bytes, actual_completed_bytes)
            progress = calculate_progress_ratio(actual_completed_bytes, total_target_bytes)

            if self.progress_callback:
                self.progress_callback(progress, actual_completed_bytes, remaining)

            # Step 10: Apply bounded backpressure pacing
            self.enforcer.enforce_pacing(self.budget.pacing_delay_seconds)

            # Step 11: Scheduled interval recalculation occurs at top of next loop

        # Step 12: Target reached
        t_gen_end = time.perf_counter()
        gen_duration = max(1e-6, t_gen_end - t_gen_start)
        
        metrics.actual_generated_bytes = actual_completed_bytes
        metrics.actual_records_generated = actual_records_generated
        metrics.measured_generation_throughput_bytes_per_sec = calculate_measured_throughput(
            actual_completed_bytes, gen_duration
        )

        return chunk_paths
